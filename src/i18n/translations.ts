export const TRANSLATIONS: Record<Language, Record<string, string>> = {
  'pt-BR': PT_BR,
  'en-US': EN_US,
  'es-ES': ES_ES,
};

/**
 * Translate a key into the requested language with `{param}` interpolation.
 * Falls back cleanly to `pt-BR`, then to the raw `key` if missing.
 */
export function t(
  lang: Language,
  key: string,
  params?: Record<string, string | number>
): string {
  const dict = TRANSLATIONS[lang] ?? TRANSLATIONS['pt-BR'];
  let value = dict[key] ?? TRANSLATIONS['pt-BR'][key] ?? key;
  if (params) {
    for (const [paramKey, paramVal] of Object.entries(params)) {
      value = value.split(`{${paramKey}}`).join(String(paramVal));
    }
  }
  return value;
}

export function getLocalizedItemName(
  lang: Language,
  itemType: WorldPickupType | string
): string {
  return t(lang, `item.${itemType}.name`);
}

export function getLocalizedItemDesc(
  lang: Language,
  itemType: WorldPickupType | string
): string {
  return t(lang, `item.${itemType}.desc`);
}

export function getTranslationKeys(): string[] {
  return Object.keys(TRANSLATIONS['pt-BR']);
}
